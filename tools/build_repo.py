def attach_refs(arts, news):
    """与 build_offline.py 同一套匹配逻辑，保证 book 与 html 里的报道一致。"""
    for a in arts:
        blob = a["title"] + "\n" + "\n".join(r["t"] for r in a["body"])
        hits = []
        for r in news:
            score = 0
            if a["cat"] in r["cats"]:
                score += 1
            ks = [k for k in r["keys"] if k in blob]
            if ks:
                score += 2 + len(ks)
            if score:
                hits.append((-score, r))
        hits.sort(key=lambda x: x[0])
        a["refs"] = [{"t": r["t"], "u": r["u"], "s": r["s"], "n": r["n"]} for _, r in hits[:4]]


def article_md(a):
    out = ["## %d. %s\n" % (a["id"], a["title"])]
    meta = ["`%s`" % a["cat"]]
    if a["col"]:
        meta.append("`%s`" % a["col"])
    meta += ["`%s%s`" % (RISK_ICON.get(r, ""), r) for r in a["risks"]]
    meta += ["`🎯%s`" % t for t in a["targets"]]
    out.append(" ".join(meta) + "\n")
    for r in a["body"]:
        t = r["t"]
        if r["k"] == "sec":
            out.append("\n**%s**\n" % t)
        elif r["k"] == "step":
            out.append("- " + t)
        elif r["k"] in ("trap", "warn", "tip", "end", "law", "money"):
            out.append("> " + t)
        else:
            out.append(t)
    if a["refs"]:
        out.append("\n**📰 相关案例与公开报道**\n")
        for r in a["refs"]:
            out.append("- [%s](%s)（%s）—— %s" % (r["t"], r["u"], r["s"], r["n"]))
    out.append("\n话题标签：%s\n" % " ".join("#" + t for t in a["tags"][:8]))
    return "\n".join(out)


def build_book(arts):
    book_dir = os.path.join(ROOT, "book")
    if not os.path.isdir(book_dir):
        os.makedirs(book_dir)
    cats = sorted({a["cat"] for a in arts}, key=lambda c: CAT_ORDER.index(c) if c in CAT_ORDER else 99)
    idx = []
    for c in cats:
        sub = [a for a in arts if a["cat"] == c]
        slug = SLUG.get(c, re.sub(r"[^\w\u4e00-\u9fff]+", "-", c))
        lines = ["# %s\n" % c, "%s\n" % CAT_INTRO.get(c, ""), "本类共 **%d 篇**。\n" % len(sub)]
        for a in sub:
            lines.append("\n----\n")
            lines.append(article_md(a))
        io.open(os.path.join(book_dir, "%s.md" % slug), "w", encoding="utf-8").write("\n".join(lines))
        idx.append((c, slug, len(sub)))
    return idx


