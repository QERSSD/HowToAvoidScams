def trap(t):
    return {"k": "trap", "t": t}


def law(t):
    return {"k": "law", "t": t}


def tip(t):
    return {"k": "tip", "t": t}


def end(t):
    return {"k": "end", "t": t}


def make_n(body):
    step_n = sum(1 for b in body if b["k"] == "step")
    trap_n = sum(1 for b in body if b["k"] in ("warn", "trap"))
    tip_n = sum(1 for b in body if b["k"] in ("tip", "end"))
    return {"step": step_n, "trap": trap_n, "tip": tip_n}


