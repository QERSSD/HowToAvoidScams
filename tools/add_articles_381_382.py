ENTRIES = [A381, A382]


def build_raw(a):
    """从结构化条目反推源稿原文（标题行按 looks_like_title 规则清洗）。"""
    title_line = "🚨 【黑产揭秘】" + a["title"].replace("：", "，")
    body_text = "\n".join(b["t"] for b in a["body"])
    tag_line = " ".join("#" + t for t in a["tags"])
    return title_line + "\n\n" + body_text + "\n\n" + tag_line + "\n"


def main():
    arts = json.load(io.open(ART, encoding="utf-8"))
    existing = {a["title"] for a in arts}
    start = max((a["id"] for a in arts), default=0)
    appended = 0
    for i, a in enumerate(ENTRIES):
        a = dict(a)
        a["id"] = start + 1 + i
        a["n"] = make_n(a["body"])
        # 字段顺序对齐现有条目
        rec = {
            "id": a["id"],
            "title": a["title"],
            "icon": a["icon"],
            "col": a["col"],
            "points": a["points"],
            "guards": a["guards"],
            "cat": a["cat"],
            "tags": a["tags"],
            "lead": a["lead"],
            "risks": a["risks"],
            "targets": a["targets"],
            "n": a["n"],
            "body": a["body"],
        }
        if a["title"] not in existing:
            arts.append(rec)
            print("追加 %d《%s》 n=%s" % (rec["id"], rec["title"][:36], rec["n"]))
            appended += 1
    with io.open(ART, "w", encoding="utf-8") as f:
        json.dump(arts, f, ensure_ascii=False, indent=1)
    print("articles.json：%d 篇（新增 %d）" % (len(arts), appended))

    # 源稿回填，保证 parse_articles.py 仍可重建
    txt = io.open(SRC, encoding="utf-8").read()
    for a in ENTRIES:
        marker = a["title"][:12]
        if marker not in txt:
            raw = build_raw(a)
            txt = txt.rstrip("\n") + "\n\n" + raw.rstrip("\n") + "\n"
            io.open(SRC, "w", encoding="utf-8").write(txt)
            print("源稿已追加：%s" % a["title"][:36])
        else:
            print("源稿已存在，跳过：%s" % a["title"][:36])


