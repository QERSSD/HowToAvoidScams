def build_raw(a):
    """从结构化条目反推源稿原文（标题行按 looks_like_title 规则清洗）。"""
    title_line = "🚨 【黑产揭秘】" + a["title"].replace("：", "，")
    body_text = "\n".join(b["t"] for b in a["body"])
    tag_line = " ".join("#" + t for t in a["tags"])
    return title_line + "\n\n" + body_text + "\n\n" + tag_line + "\n"


